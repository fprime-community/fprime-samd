#ifndef Samd21_FramPeekPokeTester_HPP
#define Samd21_FramPeekPokeTester_HPP

#include "fprime-samd/Svc/FramPeekPoke/FramPeekPoke.hpp"
#include "fprime-samd/Svc/FramPeekPoke/FramPeekPokeGTestBase.hpp"

namespace Samd21 {

class FramPeekPokeTester : public FramPeekPokeGTestBase {
  public:
    // Maximum size for histories
    static constexpr FwSizeType MAX_HISTORY_SIZE = 20;

    // Test instance ID
    static constexpr FwEnumStoreType TEST_INSTANCE_ID = 0;

    //! Simulated F-RAM window
    static constexpr FwSizeType FRAM_SIZE = 256;

    // Construction and destruction
    FramPeekPokeTester();
    ~FramPeekPokeTester();

    //! PEEK of each width reads the big-endian word and reports it.
    void testPeek();

    //! POKE of each width writes the big-endian word, leaving neighbours alone.
    void testPoke();

    //! POKE of a value wider than the width is rejected before touching F-RAM.
    void testPokeTooWide();

    //! A failed completion fails the command.
    void testAccessFailed();

    //! A request the driver rejects fails the command without a completion.
    void testRequestRejected();

    //! A command while one is outstanding is BUSY; the outstanding one completes.
    void testBusy();

    //! PEEK and POKE complete when the driver completes inside the request call.
    void testInCallCompletion();

  protected:
    //! Simulated F-RAM read
    Fram::Status from_framRead_handler(FwIndexType portNum, U32 offset, Fw::Buffer& buffer) override;

    //! Simulated F-RAM write
    Fram::Status from_framWrite_handler(FwIndexType portNum, U32 offset, Fw::Buffer& buffer) override;

  private:
    //! Component under test
    FramPeekPoke component;

    //! Simulated F-RAM contents
    U8 m_fram[FRAM_SIZE];

    //! A request is accepted and not yet completed
    bool m_pending;
    Fram::Op m_pendingOp;
    U32 m_pendingOffset;
    Fw::Buffer m_pendingBuffer;

    //! Status the next request is rejected with (ACCEPTED: take it)
    Fram::Status m_reject;

    //! Deliver the completion from inside the request call
    bool m_completeInCall;

    // ----------------------------------------------------------------------
    // Helper functions
    // ----------------------------------------------------------------------

    //! Clear history and send PEEK
    void sendPeek(U32 cmdSeq, U32 offset, FramWordWidth width);

    //! Clear history and send POKE
    void sendPoke(U32 cmdSeq, U32 offset, FramWordWidth width, U32 value);

    //! Deliver the outstanding completion with the given status
    void complete(Fram::Status status = Fram::Status::OK);

    //! Assert one command response with the given opcode, sequence and response
    void assertResponse(FwOpcodeType opcode, U32 cmdSeq, Fw::CmdResponse response);

    //! Execute and record one simulated F-RAM request
    Fram::Status framRequest(Fram::Op op, U32 offset, Fw::Buffer& buffer);

    //! Connect ports (generated by UT_AUTO_HELPERS)
    void connectPorts();

    //! Initialize components (generated by UT_AUTO_HELPERS)
    void initComponents();
};

}  // namespace Samd21

#endif
