#ifndef Samd21_CyclerSchedAdapterTester_HPP
#define Samd21_CyclerSchedAdapterTester_HPP

#include "fprime-samd/Svc/CyclerSchedAdapter/CyclerSchedAdapter.hpp"
#include "fprime-samd/Svc/CyclerSchedAdapter/CyclerSchedAdapterGTestBase.hpp"

namespace Samd21 {

class CyclerSchedAdapterTester final : public CyclerSchedAdapterGTestBase {
  public:
    // ----------------------------------------------------------------------
    // Constants
    // ----------------------------------------------------------------------

    // Maximum size of histories storing events, telemetry, and port outputs
    static constexpr FwSizeType MAX_HISTORY_SIZE = 10;

    // Instance ID supplied to the component instance under test
    static constexpr FwEnumStoreType TEST_INSTANCE_ID = 0;

    // Interleaved calls in the history-independence test
    static constexpr U32 INTERLEAVED_CALLS = 100;

  public:
    // ----------------------------------------------------------------------
    // Construction and destruction
    // ----------------------------------------------------------------------

    //! Construct object CyclerSchedAdapterTester
    CyclerSchedAdapterTester();

    //! Destroy object CyclerSchedAdapterTester
    ~CyclerSchedAdapterTester();

  public:
    // ----------------------------------------------------------------------
    // Tests (one per row of docs/sdd.md § Tests)
    // ----------------------------------------------------------------------

    //! UT-001 ForwardOnce: one activeIn call forwards exactly one schedOut call and returns false
    void testForwardOnce();

    //! UT-002 ContextPassThrough: contexts 0, 1, 7, 0xFFFFFFFF arrive at schedOut unchanged
    void testContextPassThrough();

    //! UT-003 NestedCompletion: schedOut handler has returned when activeIn returns; no call outside activeIn
    void testNestedCompletion();

    //! UT-004 Unconnected: activeIn on an instance with schedOut unconnected dies by FW_ASSERT;
    //! the connected control instance forwards once
    void testUnconnected();

    //! UT-005 HistoryIndependence: interleaved calls on two instances each forward once with
    //! their own context and return false
    void testHistoryIndependence();

    //! UT-006 NoIdleOutput: no schedOut call before the first activeIn
    void testNoIdleOutput();

  private:
    // ----------------------------------------------------------------------
    // Handlers for typed from ports
    // ----------------------------------------------------------------------

    //! Handler for from_schedOut: records whether it ran inside an activeIn call
    void from_schedOut_handler(FwIndexType portNum,  //!< The port number
                               U32 context           //!< The call order
                               ) override;

  private:
    // ----------------------------------------------------------------------
    // Helper functions
    // ----------------------------------------------------------------------

    //! Invoke activeIn on a component while flagging the call window for the handler
    bool invokeActiveIn(CyclerSchedAdapter& target,  //!< The instance to call
                        U32 context                  //!< The context to send
    );

    //! Assert one forwarded call with the given context, a false return, and the handler
    //! having run inside the activeIn window; clears the port history first
    void assertSingleForward(CyclerSchedAdapter& target,  //!< The instance to call
                             U32 context                  //!< The context to send
    );

    //! Connect ports (generated by UT_AUTO_HELPERS)
    void connectPorts();

    //! Initialize components (generated by UT_AUTO_HELPERS)
    void initComponents();

  private:
    // ----------------------------------------------------------------------
    // Member variables
    // ----------------------------------------------------------------------

    //! The component under test
    CyclerSchedAdapter component;

    //! A second instance sharing the from_schedOut port (UT-005)
    CyclerSchedAdapter second;

    //! True while invokeActiveIn is inside the activeIn call
    bool m_inActiveIn;

    //! Set by the handler when it runs inside the activeIn window
    bool m_handlerInsideActiveIn;

    //! Number of schedOut calls seen by the handler
    U32 m_handlerCalls;
};

}  // namespace Samd21

#endif
